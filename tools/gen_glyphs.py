#!/usr/bin/env python3
"""Generate the embedded glyph bitmaps for `geth --render-png`.

Renders every codepoint geth's text layer can produce (ASCII, box-drawing +
block elements, braille, and a handful of symbols) in DejaVu Sans Mono
(regular + bold) at a fixed font size, and emits two C++ sources:

  src/ui/glyphs.hpp  — cell metrics + the codepoint table + the lookup decl
  src/ui/glyphs.cpp  — the packed coverage bytes + the binary-search lookup

Each glyph is the antialiased coverage (0..255) of the character drawn on a
cw x ch canvas with the pen at (off_x, off_y) — the SAME positioning
frame2png.py uses (d.text((x*cw+off_x, y*ch+off_y), ...)), so the embedded
bitmaps reproduce the reference rendering exactly. The C++ composer tints a
glyph's coverage with the cell's truecolor foreground and alpha-blends it
over the generated background. Exception: the braille block (U+2800-28FF) is
drawn as procedural square dots (geometry measured from DejaVu Sans) because
DejaVu Sans Mono ships that block as tofu boxes.

Run once:  python3 tools/gen_glyphs.py
(DejaVu Sans Mono is required at the paths below.)
"""
import os
import sys
from string import Template

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = "/usr/share/fonts/TTF/DejaVuSansMono.ttf"
FONT_BOLD = "/usr/share/fonts/TTF/DejaVuSansMono-Bold.ttf"
FS = 22
HDR = os.path.join(ROOT, "src", "ui", "glyphs.hpp")
SRC = os.path.join(ROOT, "src", "ui", "glyphs.cpp")

HEADER = Template('''// GENERATED by tools/gen_glyphs.py — do not edit by hand.
//
// Embedded antialiased glyph coverage for `geth --render-png`. Each glyph is
// a $cw x $ch grid of 0..255 coverage (the character drawn with the pen at
// (off_x, off_y), the same positioning frame2png.py uses), for DejaVu Sans
// Mono regular and bold at font size $fs. Braille (U+2800-28FF) is drawn as
// procedural square dots instead — the mono font ships that block as tofu.
// The composer tints a glyph's coverage with the cell's foreground and
// blends it over the background.
#pragma once

#include <cstddef>
#include <cstdint>

namespace geth::ui {
constexpr int kGlyphCw = $cw;
constexpr int kGlyphCh = $ch;
constexpr int kGlyphOffX = $offx;
constexpr int kGlyphOffY = $offy;
constexpr int kGlyphSize = kGlyphCw * kGlyphCh;  // bytes per glyph

// The codepoints the text layer can produce, sorted.
constexpr std::uint32_t kCodepoints[$n] = {
    $cplist
};
constexpr std::size_t kGlyphCount = $n;

// Coverage for (codepoint, bold): a pointer into the packed table (regular
// then bold per code point), or nullptr if the code point is absent (the
// composer then leaves the cell blank — a missing glyph, not a crash).
const std::uint8_t* glyph_coverage(std::uint32_t cp, bool bold);

}  // namespace geth::ui
''')

BODY = Template('''// GENERATED by tools/gen_glyphs.py — do not edit by hand.
#include "ui/glyphs.hpp"

namespace geth::ui {
namespace {
// Packed coverage: kGlyphCount code points, regular then bold, kGlyphSize
// bytes each (row-major $cw x $ch).
const std::uint8_t kGlyphData[kGlyphCount * 2 * kGlyphSize] = {
$bytes
};
}  // namespace

const std::uint8_t* glyph_coverage(std::uint32_t cp, bool bold) {
  // Binary search the sorted codepoint table.
  std::size_t lo = 0, hi = kGlyphCount;
  while (lo < hi) {
    const std::size_t mid = lo + (hi - lo) / 2;
    if (kCodepoints[mid] < cp)
      lo = mid + 1;
    else
      hi = mid;
  }
  if (lo >= kGlyphCount || kCodepoints[lo] != cp) return nullptr;
  const std::size_t idx = (lo * 2 + (bold ? 1 : 0)) * kGlyphSize;
  return &kGlyphData[idx];
}

}  // namespace geth::ui
''')


# Braille (U+2800-28FF): DejaVu Sans Mono renders the whole braille block as
# tofu boxes, so the dots are drawn procedurally. The geometry is measured
# from DejaVu Sans (proportional — it does have braille) at the same font
# size: crisp square dots on a 2-column x 4-row grid, pen-relative.
# bit -> (column, row) in the standard braille order.
BRAILLE_BIT_POS = [(0, 0), (0, 1), (0, 2), (1, 0), (1, 1), (1, 2), (0, 3), (1, 3)]
# (col0 x0..x1, col1 x0..x1), row y0..y1 — all inclusive, pen-relative.
BRAILLE_REGULAR = ((3, 6, 10, 12), ((4, 6), (10, 12), (16, 18), (22, 24)))
BRAILLE_BOLD = ((3, 7, 10, 13), ((4, 7), (10, 13), (16, 19), (22, 25)))


def braille_bytes(cp, bold, cw, ch, off_x, off_y):
    """Coverage for one braille pattern (procedural square dots)."""
    canvas = Image.new("L", (cw, ch), 0)
    d = ImageDraw.Draw(canvas)
    cols, rows = BRAILLE_BOLD if bold else BRAILLE_REGULAR
    for bit, (col, row) in enumerate(BRAILLE_BIT_POS):
        if not ((cp & 0xFF) & (1 << bit)):
            continue
        x0, x1 = (cols[0], cols[1]) if col == 0 else (cols[2], cols[3])
        y0, y1 = rows[row]
        d.rectangle([x0 + off_x, y0 + off_y, x1 + off_x, y1 + off_y],
                    fill=255)
    return canvas.tobytes()


def codepoints():
    cps = set()
    for c in range(33, 127):            # printable ASCII (space is blank)
        cps.add(c)
    for c in range(0x2500, 0x2600):     # box drawing + block elements
        cps.add(c)
    for c in range(0x2800, 0x2900):     # braille
        cps.add(c)
    for c in (0xB0, 0xB7, 0xD7):        # degree, middle dot, multiplication
        cps.add(c)
    for c in (0x2190, 0x2191, 0x2192, 0x2193):  # arrows
        cps.add(c)
    for c in (0x2013, 0x2014, 0x2022, 0x25CB, 0x25CF):  # dashes, bullet, o/circle
        cps.add(c)
    return sorted(cps)


def byte_block(b):
    lines = []
    for i in range(0, len(b), 20):
        chunk = b[i:i + 20]
        lines.append("  " + ", ".join("0x%02x" % v for v in chunk) + ",")
    return "\n".join(lines)


def main():
    for p in (FONT, FONT_BOLD):
        if not os.path.exists(p):
            sys.exit(f"font not found: {p}")
    font = ImageFont.truetype(FONT, FS)
    font_bold = ImageFont.truetype(FONT_BOLD, FS)

    cw = int(round(font.getlength("M")))
    ch = int(round(FS * 1.28))
    lb, tb, rb, bb = font.getbbox("M")
    off_x = max(0, (cw - (rb - lb)) // 2 - lb)
    off_y = max(0, (ch - (bb - tb)) // 2 - tb)
    cps = codepoints()
    n = len(cps)
    print(f"cell {cw}x{ch} off ({off_x},{off_y}); {n} codepoints, "
          f"{n * 2} glyphs, {n * 2 * cw * ch} bytes")

    rows = []  # index = i*2 + bold
    for cp in cps:
        ch_ = chr(cp)
        for f, bold in ((font, 0), (font_bold, 1)):
            if 0x2800 <= cp <= 0x28FF:
                rows.append(braille_bytes(cp, bold, cw, ch, off_x, off_y))
            else:
                canvas = Image.new("L", (cw, ch), 0)
                d = ImageDraw.Draw(canvas)
                d.text((off_x, off_y), ch_, font=f, fill=255)
                rows.append(canvas.tobytes())

    header = HEADER.substitute(cw=cw, ch=ch, offx=off_x, offy=off_y,
                               fs=FS, n=n, cplist=",\n    ".join(map(str, cps)))
    body = BODY.substitute(cw=cw, ch=ch, n=n, bytes=byte_block(b"".join(rows)))

    os.makedirs(os.path.dirname(HDR), exist_ok=True)
    with open(HDR, "w") as f:
        f.write(header)
    with open(SRC, "w") as f:
        f.write(body)
    print(f"wrote {HDR} ({os.path.getsize(HDR)} bytes)")
    print(f"wrote {SRC} ({os.path.getsize(SRC)} bytes)")


if __name__ == "__main__":
    main()
